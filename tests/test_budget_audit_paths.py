"""Exercise the complete previously frozen synthetic replay and rejection paths."""
import copy
import hashlib
import json
import sys

import pytest

from iatonoesis import counterexample_budget_audit as audit
from iatonoesis import counterexample_followup as followup


@pytest.fixture(scope='module')
def raw():
    return followup.run()


def test_full_audit_checks_every_arm_and_preserves_comparator_order(raw):
    result = audit.audit(raw)
    assert result['instances'] == 54
    assert result['checked_original_arm_budget_records'] == 9936
    one, two = (result['metrics'][str(k)] for k in (1, 2))
    assert one['balanced_boundary'] == pytest.approx(.414931, abs=1e-6)
    assert two['symbolic_proxy'] > two['learned_feedback']
    assert two['symbolic_proxy'] == pytest.approx(.625926, abs=1e-6)
    assert set(result['symbolic_proxy_operators']).isdisjoint(result['heldout_scoring_operators'])
    with pytest.raises(ValueError, match='unexpected source'):
        audit.audit(dict(raw, test_families=[]))
    altered = copy.deepcopy(raw)
    altered['rules'][0]['denominator'] += 1
    with pytest.raises(ValueError, match='denominator'):
        audit.audit(altered)
    altered = copy.deepcopy(raw)
    altered['rules'][0]['arms'][0]['killed']['1'] = ['invented']
    with pytest.raises(ValueError, match='kill disagreement'):
        audit.audit(altered)


def test_cli_rejects_bad_digest_and_preserves_raw_receipt(raw, tmp_path, monkeypatch):
    source, output = tmp_path/'source.json', tmp_path/'audit.json'
    source.write_bytes(b'{}')
    monkeypatch.setattr(sys, 'argv', ['audit', '--source', str(source), '--output', str(output)])
    with pytest.raises(ValueError, match='hash'):
        audit.main()
    assert not output.exists()
    source.write_text(json.dumps(raw, sort_keys=True, separators=(',', ':'), allow_nan=False)+'\n')
    # Pin this locally regenerated byte stream: original frozen hash is independently
    # checked in hosted receipts, whereas numeric JSON may differ between runtimes.
    monkeypatch.setattr(audit, 'RAW_SHA', hashlib.sha256(source.read_bytes()).hexdigest())
    audit.main()
    assert json.loads(output.read_text())['checked_original_arm_budget_records'] == 9936
